using System.Text.Json.Serialization;
using Microsoft.EntityFrameworkCore;
using TableTopSheets.Api.Authentication;
using TableTopSheets.Api.Configuration;
using TableTopSheets.Api.Endpoints;
using TableTopSheets.Api.Errors;
using TableTopSheets.Api.Startup;
using TableTopSheets.Engine.Rules;
using TableTopSheets.Engine.Services;
using TableTopSheets.Persistence;
using TableTopSheets.Persistence.Postgresql;
using TableTopSheets.Persistence.Sqlite;

WebApplicationBuilder builder = WebApplication.CreateBuilder(args);

DatabaseOptions database = builder.Configuration
  .GetSection(DatabaseOptions.Section)
  .Get<DatabaseOptions>() ?? new DatabaseOptions();
builder.Services.Configure<DatabaseOptions>(builder.Configuration.GetSection(DatabaseOptions.Section));
string connectionString = database.ConnectionString(builder.Configuration);
builder.Services.AddDbContext<TableTopSheetsContext>(options =>
{
  switch (database.Provider)
  {
    case DatabaseProvider.Postgresql:
      options.UseNpgsql(connectionString, npgsql => npgsql.MigrationsAssembly(typeof(PostgresqlContextFactory).Assembly.FullName));
      break;
    default:
      options.UseSqlite(connectionString, sqlite => sqlite.MigrationsAssembly(typeof(SqliteContextFactory).Assembly.FullName));
      break;
  }
});

// rules are read from the database per request; the loader reuses what it read within the request
builder
  .Services
  .AddScoped<IRulesCatalogLoader, RulesCatalogLoader>()
  .AddScoped<ICharacterService, CharacterService>();

// Authentication:Provider switches between the database users and an OIDC identity provider
builder.AddTableTopSheetsAuthentication();

builder.Services.ConfigureHttpJsonOptions(options => options.SerializerOptions.Converters.Add(new JsonStringEnumConverter()));
builder.Services.AddProblemDetails();
builder.Services.AddExceptionHandler<ApiExceptionHandler>();
builder.Services.AddOpenApi(options => options.AddBearerScheme());

WebApplication app = builder.Build();

// the ruleset migrator migrates and seeds the database; the API only warns when it hasn't run yet
await DatabaseStartupCheck.RunAsync(app.Services);

app
  .UseExceptionHandler()
  .UseStatusCodePages()
  .UseAuthentication()
  .UseAuthorization();
app.MapOpenApi();
app.UseSwaggerUI(options =>
{
  // the UI reads the document generated by Microsoft.AspNetCore.OpenApi
  options.SwaggerEndpoint("/openapi/v1.json", "TableTopSheets API v1");
  options.RoutePrefix = "swagger";
  options.DocumentTitle = "TableTopSheets API";
  options.DisplayOperationId();
  options.EnableTryItOutByDefault();
  options.EnablePersistAuthorization();
});

// the Docker image puts the built user interface into wwwroot; without it (dotnet run) / opens the Swagger UI
bool hostsUi = app.Environment.WebRootFileProvider.GetFileInfo("index.html").Exists;
if (hostsUi)
{
  app.UseDefaultFiles();
  app.UseStaticFiles();
}
else
{
  app
    .MapGet("/", () => Results.Redirect("/swagger"))
    .ExcludeFromDescription();
}

// each returns its own route group, so they must not be chained (that would nest the groups)
app.MapAuthEndpoints();
app.MapRulesEndpoints();
app.MapCharacterEndpoints();
app.MapChoiceEndpoints();
app.MapLevelEndpoints();
app.MapInventoryEndpoints();
app.MapSpellEndpoints();

if (hostsUi)
{
  // client side routes load the app; unknown API routes stay a 404
  app
    .MapFallback("/api/{**path}", () => Results.NotFound())
    .ExcludeFromDescription();
  app.MapFallbackToFile("index.html");
}

app.Run();

